  var currentMode = DEFAULT_MODE;
  var currentLocale = resolveLocale(DEFAULT_MODE);
  var listeners = [];

  function notifyListeners() {
    for (var i = 0; i < listeners.length; i += 1) {
      try {
        listeners[i](currentLocale, currentMode);
      } catch (_) {
        // ignore
      }
    }
  }

  function applyStoredMode(val) {
    currentMode = normalizeMode(val);
    currentLocale = resolveLocale(currentMode);
  }

  var initPromise = null;
  function ready() {
    if (!initPromise) {
      initPromise = new Promise(function (resolve) {
        try {
          if (typeof chrome !== 'undefined' && chrome.storage && chrome.storage.local) {
            chrome.storage.local.get([STORAGE_KEY], function (data) {
              applyStoredMode(data ? data[STORAGE_KEY] : DEFAULT_MODE);
              resolve(currentLocale);
            });
            if (chrome.storage.onChanged && typeof chrome.storage.onChanged.addListener === 'function') {
              chrome.storage.onChanged.addListener(function (changes, areaName) {
                if (areaName === 'local' && changes[STORAGE_KEY]) {
                  applyStoredMode(changes[STORAGE_KEY].newValue);
                  notifyListeners();
                }
              });
            }
          } else {
            applyStoredMode(DEFAULT_MODE);
            resolve(currentLocale);
          }
        } catch (_) {
          applyStoredMode(DEFAULT_MODE);
          resolve(currentLocale);
        }
      });
    }
    return initPromise;
  }

  function t(key, vars) {
    var table = MESSAGES[currentLocale] || MESSAGES.en;
    var template = table[key] !== undefined ? table[key] : MESSAGES.en[key];
    if (template === undefined) return key;
    if (!vars) return template;
    return String(template).replace(/\{(\w+)\}/g, function (_, k) {
      return vars[k] !== undefined ? String(vars[k]) : '{' + k + '}';
    });
  }

  function categoryLabel(category) {
    if (!category) return t('itemLabel');
    var key = 'cat_' + category;
    var table = MESSAGES[currentLocale] || MESSAGES.en;
    if (table[key] !== undefined) return table[key];
    if (MESSAGES.en[key] !== undefined) return MESSAGES.en[key];
    return t('itemLabel');
  }

  function applyDom(doc) {
    var rootEl = doc || (typeof document !== 'undefined' ? document : null);
    if (!rootEl) return;
    if (rootEl.documentElement) {
      rootEl.documentElement.lang = currentLocale;
    }
    var i18nNodes = rootEl.querySelectorAll('[data-i18n]');
    for (var i = 0; i < i18nNodes.length; i += 1) {
      i18nNodes[i].textContent = t(i18nNodes[i].getAttribute('data-i18n'));
    }
    var phNodes = rootEl.querySelectorAll('[data-i18n-placeholder]');
    for (var j = 0; j < phNodes.length; j += 1) {
      phNodes[j].setAttribute('placeholder', t(phNodes[j].getAttribute('data-i18n-placeholder')));
    }
    var titleNodes = rootEl.querySelectorAll('[data-i18n-title]');
    for (var k = 0; k < titleNodes.length; k += 1) {
      titleNodes[k].setAttribute('title', t(titleNodes[k].getAttribute('data-i18n-title')));
    }
    var ariaNodes = rootEl.querySelectorAll('[data-i18n-aria]');
    for (var m = 0; m < ariaNodes.length; m += 1) {
      ariaNodes[m].setAttribute('aria-label', t(ariaNodes[m].getAttribute('data-i18n-aria')));
    }
  }

  function setLanguageMode(mode) {
    var next = normalizeMode(mode);
    applyStoredMode(next);
    return new Promise(function (resolve) {
      try {
        if (typeof chrome !== 'undefined' && chrome.storage && chrome.storage.local) {
          var payload = {};
          payload[STORAGE_KEY] = next;
          chrome.storage.local.set(payload, function () {
            notifyListeners();
            resolve(currentLocale);
          });
          return;
        }
      } catch (_) {
        // ignore
      }
      notifyListeners();
      resolve(currentLocale);
    });
  }

  // Begin hydrating stored locale immediately
  void ready();

  root.KeysmithI18n = {
    STORAGE_KEY: STORAGE_KEY,
    DEFAULT_MODE: DEFAULT_MODE,
    SUPPORTED_LOCALES: SUPPORTED_LOCALES,
    ready: ready,
    t: t,
    categoryLabel: categoryLabel,
    applyDom: applyDom,
    getLanguageMode: function () {
      return currentMode;
    },
    getLocale: function () {
      return currentLocale;
    },
    setLanguageMode: setLanguageMode,
    onChange: function (fn) {
      if (typeof fn === 'function') listeners.push(fn);
    }
  };
