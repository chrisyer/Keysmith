    pub fn configure_floating_rounded_window(window: &WebviewWindow) {
        let win_clone = window.clone();
        let _ = window.run_on_main_thread(move || {
            if let Ok(ns_win_ptr) = win_clone.ns_window() {
                if !ns_win_ptr.is_null() {
                    let ns_win = unsafe { &*(ns_win_ptr as *const NSWindow) };
                    ns_win.setOpaque(false);
                    let clear = NSColor::clearColor();
                    ns_win.setBackgroundColor(Some(&clear));
                    ns_win.setHasShadow(true);
                }
            }
        });
    }

    pub fn set_window_screen_capture_protection(window: &WebviewWindow, protected: bool) {
        let win_clone = window.clone();
        let _ = window.run_on_main_thread(move || {
            if let Ok(ns_win_ptr) = win_clone.ns_window() {
                if !ns_win_ptr.is_null() {
                    let ns_win = unsafe { &*(ns_win_ptr as *const NSWindow) };
                    ns_win.setSharingType(if protected {
                        NSWindowSharingType::None
                    } else {
                        NSWindowSharingType::ReadOnly
                    });
                }
            }
        });
    }

    pub fn apply_window_vibrancy(window: &WebviewWindow, enabled: bool) {
        let win_clone = window.clone();
        let _ = window.run_on_main_thread(move || {
            let _ = clear_liquid_glass(&win_clone);
            let _ = clear_vibrancy(&win_clone);
            if enabled {
                if apply_liquid_glass(
                    &win_clone,
                    LiquidGlassOptions::new(NSGlassEffectViewStyle::Regular),
                )
                .is_err()
                {
                    let _ = apply_vibrancy(
                        &win_clone,
                        NSVisualEffectMaterial::Sidebar,
                        Some(NSVisualEffectState::Active),
                        None,
                    );
                }
            }
        });
    }

    pub fn register_sleep_and_screen_lock_observers(
        on_trigger: Arc<dyn Fn(&'static str) + Send + Sync>,
    ) {
        let ws = NSWorkspace::sharedWorkspace();
        let ws_center = ws.notificationCenter();

        let sleep_cb = Arc::clone(&on_trigger);
        let sleep_block = RcBlock::new(move |_notif: NonNull<NSNotification>| {
            sleep_cb("system_sleep");
        });
        let sleep_token = unsafe {
            ws_center.addObserverForName_object_queue_usingBlock(
                Some(NSWorkspaceWillSleepNotification),
                None,
                None,
                &*sleep_block,
            )
        };
        std::mem::forget(sleep_token);

        let resign_cb = Arc::clone(&on_trigger);
        let resign_block = RcBlock::new(move |_notif: NonNull<NSNotification>| {
            resign_cb("session_resign");
        });
        let resign_token = unsafe {
            ws_center.addObserverForName_object_queue_usingBlock(
                Some(NSWorkspaceSessionDidResignActiveNotification),
                None,
                None,
                &*resign_block,
            )
        };
        std::mem::forget(resign_token);

        let dist_center = NSDistributedNotificationCenter::defaultCenter();
        let lock_name = NSString::from_str("com.apple.screenIsLocked");
        let lock_cb = on_trigger;
        let lock_block = RcBlock::new(move |_notif: NonNull<NSNotification>| {
            lock_cb("screen_locked");
        });
        let lock_token = unsafe {
            dist_center.addObserverForName_object_queue_usingBlock(
                Some(&lock_name),
                None,
                None,
                &*lock_block,
            )
        };
        std::mem::forget(lock_token);
    }

    fn launch_agent_plist_path() -> Option<PathBuf> {
        let home = std::env::var_os("HOME")?;
        Some(
            PathBuf::from(home)
                .join("Library")
                .join("LaunchAgents")
                .join(format!("{LAUNCH_AGENT_LABEL}.plist")),
        )
    }

    pub fn set_launch_at_login(enabled: bool) -> Result<(), CoreError> {
        let Some(plist_path) = launch_agent_plist_path() else {
            return Err(CoreError::Internal("无法解析 HOME 目录".to_string()));
        };
        if !enabled {
            match std::fs::remove_file(&plist_path) {
                Ok(()) => return Ok(()),
                Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(()),
                Err(e) => {
                    return Err(CoreError::Internal(format!(
                        "移除开机启动配置失败: {e}"
                    )))
                }
            }
        }

        let exe = std::env::current_exe()
            .map_err(|e| CoreError::Internal(format!("读取当前可执行文件路径失败: {e}")))?;
        let exe_str = exe.to_string_lossy();
        if let Some(parent) = plist_path.parent() {
            let _ = std::fs::create_dir_all(parent);
        }
        let xml = format!(
            r#"<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>{LAUNCH_AGENT_LABEL}</string>
  <key>ProgramArguments</key>
  <array>
    <string>{exe_str}</string>
  </array>
  <key>RunAtLoad</key>
  <true/>
</dict>
</plist>
"#
        );
        std::fs::write(&plist_path, xml)
            .map_err(|e| CoreError::Internal(format!("写入开机启动配置失败: {e}")))?;
        Ok(())
    }

    pub fn biometry_is_available() -> bool {
        let ctx = unsafe { LAContext::new() };
        unsafe {
            ctx.canEvaluatePolicy_error(LAPolicy::DeviceOwnerAuthenticationWithBiometrics)
                .is_ok()
                || ctx
                    .canEvaluatePolicy_error(LAPolicy::DeviceOwnerAuthentication)
                    .is_ok()
        }
    }

    pub fn biometry_authenticate(reason: &str) -> Result<(), CoreError> {
        let ctx = unsafe { LAContext::new() };
        let policy = unsafe {
            if ctx
                .canEvaluatePolicy_error(LAPolicy::DeviceOwnerAuthenticationWithBiometrics)
                .is_ok()
            {
                LAPolicy::DeviceOwnerAuthenticationWithBiometrics
            } else if ctx
                .canEvaluatePolicy_error(LAPolicy::DeviceOwnerAuthentication)
                .is_ok()
            {
                LAPolicy::DeviceOwnerAuthentication
            } else {
                return Err(CoreError::Biometric(
                    "此 Mac 当前未启用 Touch ID 或系统认证".to_string(),
                ));
            }
        };

        let ns_reason = NSString::from_str(if reason.is_empty() {
            "验证身份以解锁 Keysmith 保险库"
        } else {
            reason
        });

        let (tx, rx) = mpsc::channel::<Result<(), String>>();
        let block = RcBlock::new(move |success: Bool, err: *mut NSError| {
            if success.as_bool() {
                let _ = tx.send(Ok(()));
            } else if !err.is_null() {
                let err_ref = unsafe { &*err };
                let msg = err_ref.localizedDescription().to_string();
                let _ = tx.send(Err(msg));
            } else {
                let _ = tx.send(Err("生物识别验证已取消".to_string()));
            }
        });

        unsafe {
            ctx.evaluatePolicy_localizedReason_reply(policy, &ns_reason, &*block);
        }

        match rx.recv_timeout(Duration::from_secs(60)) {
            Ok(Ok(())) => Ok(()),
            Ok(Err(msg)) => Err(CoreError::Biometric(format!("Touch ID 验证失败: {msg}"))),
            Err(_) => Err(CoreError::Biometric("Touch ID 验证超时".to_string())),
        }
    }

    pub fn keychain_save(account_id: &str, key: &[u8]) -> Result<(), CoreError> {
        set_generic_password(KEYCHAIN_SERVICE, account_id, key)
            .map_err(|e| CoreError::Biometric(format!("写入 macOS Keychain 失败: {e}")))
    }

    pub fn keychain_load(account_id: &str) -> Result<Zeroizing<Vec<u8>>, CoreError> {
        let bytes = get_generic_password(KEYCHAIN_SERVICE, account_id).map_err(|e| {
            CoreError::Biometric(format!(
                "未能从 macOS Keychain 读取解锁密钥（请先用主密码解锁一次以绑定）: {e}"
            ))
        })?;
        Ok(Zeroizing::new(bytes))
    }

    pub fn keychain_delete(account_id: &str) -> Result<(), CoreError> {
        match delete_generic_password(KEYCHAIN_SERVICE, account_id) {
            Ok(()) => Ok(()),
            Err(e) => {
                if e.code() == -25300 {
                    Ok(())
                } else {
                    Err(CoreError::Biometric(format!(
                        "删除 macOS Keychain 密钥失败: {e}"
                    )))
                }
            }
        }
    }

