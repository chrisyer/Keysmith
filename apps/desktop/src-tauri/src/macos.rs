#[derive(Debug, Clone)]
struct ActiveClipboardGuard {
    digest: [u8; 32],
    label: String,
    generation: u64,
}

/// macOS `NSPasteboard` clipboard manager with `ConcealedType` + `TransientType` +
/// `AutoGeneratedType` + `CurrentHostOnly` markers and SHA-256-verified auto-clear countdown.
pub struct MacosClipboard {
    app: AppHandle,
    state: Arc<Mutex<Option<ActiveClipboardGuard>>>,
    next_generation: Arc<Mutex<u64>>,
}

impl MacosClipboard {
    pub fn new(app: AppHandle) -> Self {
        Self {
            app,
            state: Arc::new(Mutex::new(None)),
            next_generation: Arc::new(Mutex::new(0)),
        }
    }

    fn bump_generation(&self) -> u64 {
        let mut gen_guard = self.next_generation.lock().unwrap_or_else(|e| e.into_inner());
        *gen_guard = gen_guard.wrapping_add(1);
        *gen_guard
    }
}

impl ClipboardManager for MacosClipboard {
    fn copy_secret(
        &self,
        text: &str,
        label: &str,
        is_sensitive: bool,
        clear_after_secs: u64,
    ) -> Result<(), CoreError> {
        macos_impl::pasteboard_write(text, is_sensitive)?;

        let generation = self.bump_generation();

        if !is_sensitive || clear_after_secs == 0 {
            {
                let mut guard = self.state.lock().unwrap_or_else(|e| e.into_inner());
                *guard = None;
            }
            let _ = self
                .app
                .emit(EVENT_CLIPBOARD_TICK, Option::<ClipboardTickPayload>::None);
            return Ok(());
        }

        let digest: [u8; 32] = Sha256::digest(text.as_bytes()).into();
        let label_owned = label.to_string();

        {
            let mut guard = self.state.lock().unwrap_or_else(|e| e.into_inner());
            *guard = Some(ActiveClipboardGuard {
                digest,
                label: label_owned.clone(),
                generation,
            });
        }

        let _ = self.app.emit(
            EVENT_CLIPBOARD_TICK,
            Some(ClipboardTickPayload {
                label: label_owned.clone(),
                remaining_seconds: clear_after_secs,
                total_seconds: clear_after_secs,
            }),
        );

        let app = self.app.clone();
        let state = Arc::clone(&self.state);
        let gen_counter = Arc::clone(&self.next_generation);

        tauri::async_runtime::spawn(async move {
            for remaining in (0..clear_after_secs).rev() {
                tokio::time::sleep(Duration::from_secs(1)).await;

                let current_gen = *gen_counter.lock().unwrap_or_else(|e| e.into_inner());
                if current_gen != generation {
                    return;
                }

                if remaining > 0 {
                    let _ = app.emit(
                        EVENT_CLIPBOARD_TICK,
                        Some(ClipboardTickPayload {
                            label: label_owned.clone(),
                            remaining_seconds: remaining,
                            total_seconds: clear_after_secs,
                        }),
                    );
                } else {
                    let should_clear = {
                        let mut guard = state.lock().unwrap_or_else(|e| e.into_inner());
                        let matches_gen = guard
                            .as_ref()
                            .map(|g| g.generation == generation)
                            .unwrap_or(false);
                        if matches_gen {
                            let expected = guard.as_ref().map(|g| g.digest);
                            *guard = None;
                            expected
                        } else {
                            None
                        }
                    };

                    if let Some(expected_digest) = should_clear {
                        let _ = macos_impl::pasteboard_clear_if_matches(&expected_digest);
                        let _ = app.emit(EVENT_CLIPBOARD_TICK, Option::<ClipboardTickPayload>::None);
                        let _ = app.emit(
                            EVENT_CLIPBOARD_CLEARED,
                            ClipboardClearedPayload {
                                label: label_owned.clone(),
                            },
                        );
                    }
                }
            }
        });

        Ok(())
    }

    fn clear_now(&self) -> Result<(), CoreError> {
        self.bump_generation();
        let active = {
            let mut guard = self.state.lock().unwrap_or_else(|e| e.into_inner());
            guard.take()
        };

        let label = active
            .as_ref()
            .map(|a| a.label.clone())
            .unwrap_or_else(|| "敏感内容".to_string());

        if let Some(active) = active {
            macos_impl::pasteboard_clear_if_matches(&active.digest)?;
        } else {
            macos_impl::pasteboard_clear_unconditional()?;
        }

        let _ = self
            .app
            .emit(EVENT_CLIPBOARD_TICK, Option::<ClipboardTickPayload>::None);
        let _ = self
            .app
            .emit(EVENT_CLIPBOARD_CLEARED, ClipboardClearedPayload { label });
        Ok(())
    }
}

