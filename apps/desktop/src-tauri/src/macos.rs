    pub fn pasteboard_write(text: &str, is_sensitive: bool) -> Result<(), CoreError> {
        let pb = NSPasteboard::generalPasteboard();

        let ns_text = NSString::from_str(text);
        let ns_string_type = unsafe { NSPasteboardTypeString };

        if is_sensitive {
            pb.prepareForNewContentsWithOptions(NSPasteboardContentsOptions::CurrentHostOnly);
            let concealed = NSString::from_str(CONCEALED_TYPE);
            let transient = NSString::from_str(TRANSIENT_TYPE);
            let auto_gen = NSString::from_str(AUTO_GENERATED_TYPE);
            let types = NSArray::from_slice(&[ns_string_type, &*concealed, &*transient, &*auto_gen]);
            unsafe {
                pb.declareTypes_owner(&types, None);
            }
            let ok = pb.setString_forType(&ns_text, ns_string_type);
            if !ok {
                return Err(CoreError::Clipboard("写入 NSPasteboard 失败".to_string()));
            }
            let empty = NSData::new();
            let _ = pb.setData_forType(Some(&empty), &concealed);
            let _ = pb.setData_forType(Some(&empty), &transient);
            let _ = pb.setData_forType(Some(&empty), &auto_gen);
        } else {
            pb.clearContents();
            let types = NSArray::from_slice(&[ns_string_type]);
            unsafe {
                pb.declareTypes_owner(&types, None);
            }
            let ok = pb.setString_forType(&ns_text, ns_string_type);
            if !ok {
                return Err(CoreError::Clipboard("写入 NSPasteboard 失败".to_string()));
            }
        }

        Ok(())
    }

    pub fn pasteboard_clear_if_matches(expected_digest: &[u8; 32]) -> Result<(), CoreError> {
        let pb = NSPasteboard::generalPasteboard();
        let ns_string_type = unsafe { NSPasteboardTypeString };
        if let Some(current) = pb.stringForType(ns_string_type) {
            let current_str = current.to_string();
            let current_digest: [u8; 32] = Sha256::digest(current_str.as_bytes()).into();
            if &current_digest == expected_digest {
                pb.clearContents();
            }
        }
        Ok(())
    }

    pub fn pasteboard_clear_unconditional() -> Result<(), CoreError> {
        let pb = NSPasteboard::generalPasteboard();
        pb.clearContents();
        Ok(())
    }

    pub fn pasteboard_read_image_png_base64() -> Option<String> {
        let pb = NSPasteboard::generalPasteboard();
        let png_type = unsafe { NSPasteboardTypePNG };
        if let Some(png_data) = pb.dataForType(png_type) {
            let bytes = png_data.to_vec();
            if !bytes.is_empty() {
                return Some(B64.encode(&bytes));
            }
        }

        let tiff_type = unsafe { NSPasteboardTypeTIFF };
        if let Some(tiff_data) = pb.dataForType(tiff_type) {
            if let Some(rep) = NSBitmapImageRep::imageRepWithData(&tiff_data) {
                let empty_props = NSDictionary::new();
                if let Some(png_data) = unsafe {
                    rep.representationUsingType_properties(NSBitmapImageFileType::PNG, &empty_props)
                } {
                    let bytes = png_data.to_vec();
                    if !bytes.is_empty() {
                        return Some(B64.encode(&bytes));
                    }
                }
            }
        }

        None
    }

