use std::time::Duration;

use rand::{rngs::OsRng, RngCore};
use reqwest::Client;
use serde_json::{json, Value};

use crate::domain::{extract_domain, MaskedEmailConfig, MaskedEmailProvider};
use crate::error::CoreError;

use super::WORD_LIST;

fn random_hex(bytes_len: usize) -> String {
    let mut buf = vec![0u8; bytes_len];
    OsRng.fill_bytes(&mut buf);
    let mut out = String::with_capacity(bytes_len * 2);
    for b in buf {
        use std::fmt::Write;
        let _ = write!(&mut out, "{b:02x}");
    }
    out
}

fn pick_word() -> &'static str {
    let idx = (OsRng.next_u32() as usize) % WORD_LIST.len();
    WORD_LIST[idx]
}

fn sanitize_domain_prefix(domain_hint: Option<&str>) -> Option<String> {
    let raw = domain_hint?.trim();
    if raw.is_empty() {
        return None;
    }
    let host = extract_domain(raw).to_ascii_lowercase();
    let label = host.split('.').next().unwrap_or("").trim();
    let clean: String = label
        .chars()
        .filter(|c| c.is_ascii_alphanumeric() || *c == '-')
        .take(20)
        .collect();
    if clean.is_empty() || clean == "localhost" {
        None
    } else {
        Some(clean)
    }
}

pub fn generate_catch_all_alias(
    catch_all_domain: &str,
    domain_hint: Option<&str>,
) -> Result<String, CoreError> {
    let dom = catch_all_domain
        .trim()
        .trim_start_matches('@')
        .to_ascii_lowercase();
    if dom.is_empty() || !dom.contains('.') {
        return Err(CoreError::Validation(
            "请先配置有效的自定义邮箱域名 (例如 example.com)".to_string(),
        ));
    }
    let suffix = random_hex(2);
    let local = match sanitize_domain_prefix(domain_hint) {
        Some(prefix) => format!("{prefix}.{word}{suffix}", word = pick_word()),
        None => format!("{w1}.{w2}{suffix}", w1 = pick_word(), w2 = pick_word()),
    };
    Ok(format!("{local}@{dom}"))
}

pub async fn generate_masked_email(
    config: &MaskedEmailConfig,
    domain_hint: Option<&str>,
) -> Result<String, CoreError> {
    let clean_hint_host = domain_hint
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .map(extract_domain)
        .filter(|h| !h.is_empty());

    match config.provider {
        MaskedEmailProvider::CatchAll => {
            generate_catch_all_alias(&config.domain, clean_hint_host.as_deref())
        }
        MaskedEmailProvider::SimpleLogin => {
            let api_key = config.api_key.trim();
            if api_key.is_empty() {
                return Err(CoreError::Validation(
                    "请先在设置中配置 SimpleLogin API Key".to_string(),
                ));
            }
            let base = config
                .api_base_url
                .as_deref()
                .map(str::trim)
                .filter(|s| !s.is_empty())
                .unwrap_or("https://app.simplelogin.io")
                .trim_end_matches('/');
            let client = build_alias_http_client()?;
            let mut req = client
                .post(format!("{base}/api/alias/random/new"))
                .header("Authentication", api_key)
                .json(&json!({
                    "note": match &clean_hint_host {
                        Some(h) => format!("Generated by Keysmith for {h}"),
                        None => "Generated by Keysmith".to_string(),
                    }
                }));
            if let Some(ref h) = clean_hint_host {
                req = req.query(&[("hostname", h.as_str())]);
            }
            let resp = req
                .send()
                .await
                .map_err(|e| CoreError::Network(format!("请求 SimpleLogin 失败: {e}")))?;
            let status = resp.status();
            let body: Value = resp
                .json()
                .await
                .map_err(|e| CoreError::Network(format!("解析 SimpleLogin 响应失败: {e}")))?;
            if !status.is_success() {
                let err_msg = body
                    .get("error")
                    .and_then(|v| v.as_str())
                    .unwrap_or("SimpleLogin 接口返回错误");
                return Err(CoreError::Network(format!("{err_msg} (HTTP {status})")));
            }
            body.get("alias")
                .and_then(|v| v.as_str())
                .map(|s| s.trim().to_string())
                .filter(|s| s.contains('@'))
                .ok_or_else(|| CoreError::Network("SimpleLogin 未返回有效邮箱别名".to_string()))
        }
        MaskedEmailProvider::AddyIo => {
            let api_key = config.api_key.trim();
            if api_key.is_empty() {
                return Err(CoreError::Validation(
                    "请先在设置中配置 addy.io API Key".to_string(),
                ));
            }
            let base = config
                .api_base_url
                .as_deref()
                .map(str::trim)
                .filter(|s| !s.is_empty())
                .unwrap_or("https://app.addy.io")
                .trim_end_matches('/');
            let client = build_alias_http_client()?;
            let mut payload = serde_json::Map::new();
            let custom_dom = config.domain.trim();
            if !custom_dom.is_empty() {
                payload.insert("domain".to_string(), Value::String(custom_dom.to_string()));
            }
            payload.insert(
                "description".to_string(),
                Value::String(match &clean_hint_host {
                    Some(h) => format!("Keysmith ({h})"),
                    None => "Generated by Keysmith".to_string(),
                }),
            );
            let resp = client
                .post(format!("{base}/api/v1/aliases"))
                .bearer_auth(api_key)
                .header("Accept", "application/json")
                .header("X-Requested-With", "XMLHttpRequest")
                .json(&Value::Object(payload))
                .send()
                .await
                .map_err(|e| CoreError::Network(format!("请求 addy.io 失败: {e}")))?;
            let status = resp.status();
            let body: Value = resp
                .json()
                .await
                .map_err(|e| CoreError::Network(format!("解析 addy.io 响应失败: {e}")))?;
            if !status.is_success() {
                let err_msg = body
                    .get("message")
                    .and_then(|v| v.as_str())
                    .unwrap_or("addy.io 接口返回错误");
                return Err(CoreError::Network(format!("{err_msg} (HTTP {status})")));
            }
            body.get("data")
                .and_then(|d| d.get("email"))
                .or_else(|| body.get("email"))
                .and_then(|v| v.as_str())
                .map(|s| s.trim().to_string())
                .filter(|s| s.contains('@'))
                .ok_or_else(|| CoreError::Network("addy.io 未返回有效邮箱别名".to_string()))
        }
        MaskedEmailProvider::Fastmail => {
            let api_key = config.api_key.trim();
            if api_key.is_empty() {
                return Err(CoreError::Validation(
                    "请先在设置中配置 Fastmail API Token".to_string(),
                ));
            }
            let base = config
                .api_base_url
                .as_deref()
                .map(str::trim)
                .filter(|s| !s.is_empty())
                .unwrap_or("https://api.fastmail.com")
                .trim_end_matches('/');
            let client = build_alias_http_client()?;
            let session_resp = client
                .get(format!("{base}/jmap/session"))
                .bearer_auth(api_key)
                .send()
                .await
                .map_err(|e| CoreError::Network(format!("获取 Fastmail JMAP 会话失败: {e}")))?;
            if !session_resp.status().is_success() {
                return Err(CoreError::Network(format!(
                    "Fastmail 认证失败 (HTTP {})",
                    session_resp.status()
                )));
            }
            let session_json: Value = session_resp
                .json()
                .await
                .map_err(|e| CoreError::Network(format!("解析 Fastmail JMAP 会话失败: {e}")))?;
            let api_url = session_json
                .get("apiUrl")
                .and_then(|v| v.as_str())
                .map(|s| s.to_string())
                .unwrap_or_else(|| format!("{base}/jmap/api/"));
            let account_id = session_json
                .get("primaryAccounts")
                .and_then(|p| p.get("https://www.fastmail.com/dev/maskedemail"))
                .and_then(|v| v.as_str())
                .or_else(|| {
                    session_json
                        .get("accounts")
                        .and_then(|a| a.as_object())
                        .and_then(|m| m.keys().next().map(String::as_str))
                })
                .ok_or_else(|| CoreError::Network("Fastmail JMAP 未找到可用账户 ID".to_string()))?;

            let mut create_obj = json!({
                "state": "enabled",
                "description": "Generated by Keysmith",
            });
            if let Some(ref h) = clean_hint_host {
                create_obj["forDomain"] = Value::String(format!("https://{h}"));
            }
            if !config.domain.trim().is_empty() {
                create_obj["emailDomain"] = Value::String(config.domain.trim().to_string());
            }

            let jmap_req = json!({
                "using": [
                    "urn:ietf:params:jmap:core",
                    "https://www.fastmail.com/dev/maskedemail"
                ],
                "methodCalls": [[
                    "MaskedEmail/set",
                    {
                        "accountId": account_id,
                        "create": {
                            "k1": create_obj
                        }
                    },
                    "0"
                ]]
            });

            let call_resp = client
                .post(&api_url)
                .bearer_auth(api_key)
                .json(&jmap_req)
                .send()
                .await
                .map_err(|e| CoreError::Network(format!("创建 Fastmail Masked Email 失败: {e}")))?;
            let call_json: Value = call_resp
                .json()
                .await
                .map_err(|e| CoreError::Network(format!("解析 Fastmail JMAP 响应失败: {e}")))?;
            call_json
                .get("methodResponses")
                .and_then(|r| r.get(0))
                .and_then(|m| m.get(1))
                .and_then(|res| res.get("created"))
                .and_then(|c| c.get("k1"))
                .and_then(|k| k.get("email"))
                .and_then(|e| e.as_str())
                .map(|s| s.trim().to_string())
                .filter(|s| s.contains('@'))
                .ok_or_else(|| CoreError::Network("Fastmail 未返回有效 Masked Email".to_string()))
        }
        MaskedEmailProvider::DuckDuckGo => {
            let api_key = config.api_key.trim();
            if api_key.is_empty() {
                return Err(CoreError::Validation(
                    "请先在设置中配置 DuckDuckGo Email Token".to_string(),
                ));
            }
            let base = config
                .api_base_url
                .as_deref()
                .map(str::trim)
                .filter(|s| !s.is_empty())
                .unwrap_or("https://quack.duckduckgo.com")
                .trim_end_matches('/');
            let client = build_alias_http_client()?;
            let resp = client
                .post(format!("{base}/api/email/addresses"))
                .bearer_auth(api_key)
                .send()
                .await
                .map_err(|e| CoreError::Network(format!("请求 DuckDuckGo 邮箱别名失败: {e}")))?;
            let status = resp.status();
            let body: Value = resp
                .json()
                .await
                .map_err(|e| CoreError::Network(format!("解析 DuckDuckGo 响应失败: {e}")))?;
            if !status.is_success() {
                return Err(CoreError::Network(format!(
                    "DuckDuckGo 接口返回错误 (HTTP {status})"
                )));
            }
            let addr = body
                .get("address")
                .and_then(|v| v.as_str())
                .map(str::trim)
                .filter(|s| !s.is_empty())
                .ok_or_else(|| CoreError::Network("DuckDuckGo 未返回别名地址".to_string()))?;
            if addr.contains('@') {
                Ok(addr.to_string())
            } else {
                Ok(format!("{addr}@duck.com"))
            }
        }
    }
}

fn build_alias_http_client() -> Result<Client, CoreError> {
    Client::builder()
        .timeout(Duration::from_secs(12))
        .user_agent("Keysmith/0.2")
        .build()
        .map_err(|e| CoreError::Internal(format!("初始化 HTTP 客户端失败: {e}")))
}
